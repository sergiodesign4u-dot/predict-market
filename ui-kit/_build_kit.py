    brand_html = "".join(
        f'<figure class="kit-ico"><svg class="kit-brandic" viewBox="0 0 24 24" aria-hidden="true">{i}</svg>'
        f'<figcaption>{_brand_name(i)}</figcaption></figure>' for i in brand)
