def _build_icons_section():
    named = "".join(
        f'<figure class="kit-ico"><svg class="ic" viewBox="0 0 24 24" aria-hidden="true"><use href="#{i}"/></svg>'
        f'<figcaption>{label}</figcaption><code>#{i}</code></figure>'
        for i, label in NAMED_ICONS)
    seen = {}
    svg_re = re.compile(r'<svg\b[^>]*viewBox="0 0 24 24"[^>]*>(.*?)</svg>', re.S)
    for pg in sorted(UV.glob("*.html")):
        for m in svg_re.finditer(pg.read_text(encoding="utf-8")):
            inner = re.sub(r"\s+", " ", m.group(1)).strip()
            if "<use" in inner or not inner:
                continue
            seen.setdefault(inner, True)
